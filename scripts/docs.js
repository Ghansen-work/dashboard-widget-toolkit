#!/usr/bin/env node
'use strict';
/*
  Generates widget documentation from the schemas, so docs never drift from
  what the validator enforces.

    widgets/CATALOG.md        One-screen index Computer reads to pick widgets.
    widgets/<type>/README.md  Full reference for one widget.

  Usage:
    node scripts/docs.js           Write the docs.
    node scripts/docs.js --check   Exit 1 if the docs are out of date (used in tests).
*/
const fs = require('fs');
const path = require('path');
const { WIDGETS_DIR, loadWidgets } = require('./lib/toolkit');

const GENERATED = '<!-- Generated by scripts/docs.js from schema.json. Edit the schema, then run `npm run docs`. -->';

function typeLabel(schema) {
  if (schema.const !== undefined) return `\`${JSON.stringify(schema.const)}\``;
  if (schema.enum) return schema.enum.map((v) => `\`${JSON.stringify(v)}\``).join(' | ');
  const types = [].concat(schema.type || 'any');
  return types.map((t) => {
    if (t === 'array' && schema.items) return `list of ${typeLabel(schema.items)}`;
    return t;
  }).join(' or ');
}

function cell(text) {
  return String(text || '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
}

function fieldRows(schema, prefix = '') {
  const rows = [];
  const required = new Set(schema.required || []);
  for (const [name, prop] of Object.entries(schema.properties || {})) {
    const field = prefix + name;
    const extra = prop.default !== undefined ? ` Default: \`${JSON.stringify(prop.default)}\`.` : '';
    rows.push(`| \`${field}\` | ${cell(typeLabel(prop))} | ${required.has(name) ? 'yes' : ''} | ${cell((prop.description || '') + extra)} |`);
    if (prop.type === 'object' && prop.properties) rows.push(...fieldRows(prop, `${field}.`));
    if (prop.type === 'array' && prop.items && prop.items.properties) rows.push(...fieldRows(prop.items, `${field}[].`));
  }
  return rows;
}

function widgetReadme(widget) {
  const raw = widget.raw;
  const example = fs.readFileSync(widget.exampleFile, 'utf8').trim();
  const sizes = raw['x-sizes'].map((s) => (s === raw['x-default-size'] ? `${s} (default)` : s)).join(', ');
  const checks = (raw['x-checks'] || []).map((c) => `- ${c}`).join('\n');
  return [
    `# ${raw.title} (\`${widget.type}\`)`,
    '',
    GENERATED,
    '',
    raw.description,
    '',
    `**Use when:** ${raw['x-use-when']}`,
    '',
    `**Don't use when:** ${raw['x-dont-use-when']}`,
    '',
    `**Sizes:** ${sizes}`,
    '',
    '## Fields',
    '',
    'Fields from `id` to `note` are shared by every widget.',
    '',
    '| Field | Type | Required | Description |',
    '| --- | --- | --- | --- |',
    ...fieldRows(widget.schema),
    '',
    '## Example',
    '',
    '```json',
    example,
    '```',
    ...(checks ? ['', '## Checks beyond the schema', '', checks] : []),
    ''
  ].join('\n');
}

function catalog(widgets) {
  const rows = Object.values(widgets).map((w) => {
    const r = w.raw;
    return `| [\`${w.type}\`](${w.type}/README.md) | ${cell(r['x-use-when'])} | ${cell(r['x-dont-use-when'])} | ${r['x-sizes'].join(', ')} |`;
  });
  return [
    '# Widget catalog',
    '',
    GENERATED.replace('from schema.json', 'from each widget\'s schema.json'),
    '',
    'Pick widgets from this list only. Before using a widget, open its README for the exact fields and an example.',
    '',
    'Grid sizes: S = 3, M = 6, L = 9, full = 12 columns. Each row of widgets should add up to 12.',
    '',
    '| Widget | Use when | Don\'t use when | Sizes |',
    '| --- | --- | --- | --- |',
    ...rows,
    ''
  ].join('\n');
}

function expectedDocs() {
  const widgets = loadWidgets();
  const files = { [path.join(WIDGETS_DIR, 'CATALOG.md')]: catalog(widgets) };
  for (const w of Object.values(widgets)) files[path.join(w.dir, 'README.md')] = widgetReadme(w);
  return files;
}

function main() {
  const check = process.argv.includes('--check');
  const stale = [];
  let wrote = 0;
  for (const [file, content] of Object.entries(expectedDocs())) {
    const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
    if (current === content) continue;
    if (check) stale.push(path.relative(process.cwd(), file));
    else {
      fs.writeFileSync(file, content);
      wrote++;
      console.log(`Wrote ${path.relative(process.cwd(), file)}`);
    }
  }
  if (check && stale.length) {
    console.error(`Docs are out of date: ${stale.join(', ')}. Run \`npm run docs\`.`);
    return 1;
  }
  if (!check && !wrote) console.log('Docs are up to date.');
  return 0;
}

if (require.main === module) process.exitCode = main();
module.exports = { expectedDocs };
